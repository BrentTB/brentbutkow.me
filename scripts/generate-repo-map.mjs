#!/usr/bin/env node
// Walks src/ and writes REPO_MAP.md — a grep-friendly file → exports index for Claude.
// Run via `npm run repo-map`. Husky pre-commit keeps it fresh.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const ROOT = process.cwd()
const SRC = join(ROOT, 'src')

const INCLUDE = /\.(ts|tsx)$/
const SKIP = [/\.test\.(ts|tsx)$/, /\.d\.ts$/]

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full, files)
    else if (INCLUDE.test(entry) && !SKIP.some((r) => r.test(entry))) files.push(full)
  }
  return files
}

const EXPORT_DECL =
  /^export\s+(?:async\s+)?(?:const|let|var|function|class|type|interface|enum)\s+(\w+)/gm
const EXPORT_BLOCK = /^export\s+\{([^}]+)\}/gm

function extractExports(content) {
  const names = new Set()
  for (const m of content.matchAll(EXPORT_DECL)) names.add(m[1])
  for (const m of content.matchAll(EXPORT_BLOCK)) {
    for (const part of m[1].split(',')) {
      const name = part
        .trim()
        .split(/\s+as\s+/)[0]
        .trim()
      if (name) names.add(name)
    }
  }
  return [...names]
}

const files = walk(SRC).sort()

const lines = [
  '# REPO_MAP',
  '',
  'Auto-generated by `npm run repo-map`. Pre-commit hook keeps it fresh, do not edit by hand.',
  '',
  'Format: `<file>  <exported symbols>`. Use this to locate code instead of grepping source.',
  '',
  '```',
]

let lastDir = null
for (const file of files) {
  const rel = relative(ROOT, file)
  const ix = rel.lastIndexOf(sep)
  const dir = rel.slice(0, ix)
  const name = rel.slice(ix + 1)
  if (dir !== lastDir) {
    if (lastDir !== null) lines.push('')
    lines.push(`${dir}/`)
    lastDir = dir
  }
  const exports = extractExports(readFileSync(file, 'utf8'))
  const label = exports.length ? exports.join(', ') : '(no named exports)'
  lines.push(`  ${name.padEnd(42)} ${label}`)
}
lines.push('```', '')

writeFileSync(join(ROOT, 'REPO_MAP.md'), lines.join('\n'))
console.log(`Wrote REPO_MAP.md (${files.length} files)`)
